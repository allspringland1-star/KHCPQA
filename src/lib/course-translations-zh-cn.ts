export type CourseZhCnTranslation = {
  certificationNote: string;
  curriculumItems: string[];
  duration: string;
  imageAlt: string;
  overview: string;
  recommendedFor: string[];
  sectionTitles: string[];
  seoDescription: string;
  seoTitle: string;
  summary: string;
  title: string;
  topics: Array<{ detail: string; title: string }>;
};

function defineCourse(
  title: string,
  summary: string,
  overview: string,
  duration: string,
  topics: string[],
  recommendedFor: string[],
  certificationNote: string,
  sectionTitles: string[] = ["主要培训内容", "实操课程", "就业与发展方向", "课程说明", "应用领域", "相关课程"]
): CourseZhCnTranslation {
  const curriculumItems = topics.slice(0, Math.max(3, Math.min(5, topics.length)));
  return {
    certificationNote,
    curriculumItems,
    duration,
    imageAlt: `${title}课程图片`,
    overview,
    recommendedFor,
    sectionTitles,
    seoDescription: summary,
    seoTitle: `${title} | KAHC`,
    summary,
    title,
    topics: topics.map((topic) => ({
      detail: `通过理论说明、示范和反复练习，系统掌握${topic}。`,
      title: topic
    }))
  };
}

